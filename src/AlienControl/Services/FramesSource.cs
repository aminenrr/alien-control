using System;
using System.Diagnostics;
using System.IO;
using System.Runtime.InteropServices;
using System.Threading;

namespace AlienControl.Services;

/// <summary>
/// beta1.3-ov: frametimes of the foreground game from PresentMon (GameTechDev, MIT), the same ETW data RTSS-free tools
/// use. PresentMon runs as a separate process (tools\PresentMon\PresentMon.exe, no injection, anti cheat safe) and
/// writes one CSV line per Present() to stdout. Only the cheapest tracking is on (no display, GPU or input tracking),
/// since the overlay only needs MsBetweenPresents, the frametime MangoHud shows.
///
/// Lifecycle: Start when the overlay goes from off to a level, Stop when it goes off. Nothing runs while off.
/// The child is put in a kill-on-close job object, so it dies with the app even on a crash or a Task Manager kill,
/// ov.4 (Defender flagged ov.3 as Behavior:Win32/DefenseEvasion.A!ml): we never stop an ETW session ourselves any more.
/// Stop asks PresentMon to quit the way its own Ctrl+C handler does (WM_QUIT to its "PresentMon" message window), so
/// PresentMon closes its own session. No second PresentMon with --terminate_existing_session, and --stop_existing_session
/// is passed only after PresentMon reported a leftover session of our name (it was killed: crash, Task Manager).
/// Going off is debounced (StopSoon), so flipping F4 or the toggle doesn't churn processes.
/// </summary>
public sealed class FramesSource : IDisposable
{
    public const string SessionName = "AlienControlsOverlay";

    /// <summary>One frame: when it arrived (Stopwatch ticks), PresentMon's own CPUStartTime in seconds (exact even when
    /// stdout arrives in bursts) and its frametime in ms. Gen and Lat are only filled in extended mode: Gen = the frame
    /// was generated by a driver / SDK (frame generation), Lat = latency in ms (NaN when unknown), PcLat = Lat is the
    /// Reflex style PC latency (input to display) rather than PresentMon's display latency (frame start to display).</summary>
    public readonly record struct Frame(long Ticks, double T, float Ms, bool Gen = false, float Lat = float.NaN, bool PcLat = false);

    /// <summary>The window's stats: real fps (app rendered frames), generated fps (frame generation), average frametime of
    /// all presents, and latency (NaN when none).</summary>
    public readonly record struct Stats(double Fps, double GenFps, double AvgMs, double LatMs, bool PcLat);

    private readonly object _lock = new();
    private readonly Frame[] _ring = new Frame[4096];
    private int _head, _count;
    private Process? _proc;
    private Thread? _reader;
    private volatile bool _running;
    private int _targetPid;
    private string _targetApp = "";
    private string _runtime = "";
    private long _lastFgCheck;
    private IntPtr _job;

    public static string ExePath => Path.Combine(AppContext.BaseDirectory, "tools", "PresentMon", "PresentMon.exe");
    public static bool Available => File.Exists(ExePath);

    public bool Running => _running;

    /// <summary>Latency and frame gen mode (Amine's hard toggle, off by default). On: PresentMon also tracks the display,
    /// the frame type and PC latency. Off: none of that is collected. Changing it restarts a running session.</summary>
    public bool Extended { get; private set; }

    public void SetExtended(bool on)
    {
        if (on == Extended) return;
        Extended = on;
        _tier = 0;
        if (_running && !StopPending) { Stop(); Start(); }
        else if (_running) Stop();   // was about to go off anyway: next Start uses the new mode
    }

    /// <summary>PresentMon command line for a mode. Off = the lean set (no display, GPU or input tracking).
    /// Extended keeps GPU and input off and adds display, frame type and PC latency; tier 1 drops the two
    /// instrumentation flags (fallback if this PresentMon build rejects them).</summary>
    internal static string Args(bool extended, int tier = 0, bool stopExisting = false)
    {
        var a = $"--output_stdout --no_console_stats --session_name {SessionName} " + (stopExisting ? "--stop_existing_session " : "") +
                "--no_track_gpu --no_track_input --exclude dwm.exe --exclude AlienControl.exe";
        if (!extended) return a + " --no_track_display";
        return tier == 0 ? a + " --track_frame_type --track_pc_latency" : a;
    }

    private int _tier;
    private long _startedAt;
    /// <summary>Last error (PresentMon missing, failed to start, exited). Null while healthy.</summary>
    public string? Error { get; private set; }

    /// <summary>Exe name of the process the frames belong to (the foreground window's), empty when none presents.</summary>
    public string TargetApp { get { lock (_lock) return _targetApp; } }
    public int TargetPid { get { lock (_lock) return _targetPid; } }
    /// <summary>PresentMon's PresentRuntime for the target (DXGI, D3D9, Other). The overlay maps it to an engine label.</summary>
    public string Runtime { get { lock (_lock) return _runtime; } }

    private readonly object _life = new();

    public bool Start() { lock (_life) return StartCore(); }

    private bool StartCore()
    {
        CancelStopSoon();
        if (_running) return true;
        WaitForStopping();
        Error = null;
        if (!Available) { Error = "PresentMon is missing (tools\\PresentMon)."; Log.Info("Frames", Error); return false; }
        try
        {
            _sawStale = false;
            var psi = new ProcessStartInfo(ExePath, Args(Extended, _tier, _staleSession))
            {
                CreateNoWindow = true, UseShellExecute = false, RedirectStandardOutput = true, RedirectStandardError = true,
                WorkingDirectory = Path.GetDirectoryName(ExePath)!,
            };
            var p = Process.Start(psi)!;
            AttachToJob(p);
            p.ErrorDataReceived += (_, e) =>
            {
                if (string.IsNullOrWhiteSpace(e.Data)) return;
                Log.Info("PresentMon", e.Data!);
                if (e.Data!.Contains("already running", StringComparison.OrdinalIgnoreCase)) _sawStale = true;
            };
            p.BeginErrorReadLine();
            _proc = p;
            _running = true;
            _startedAt = Stopwatch.GetTimestamp();
            lock (_lock) { _head = 0; _count = 0; _targetPid = 0; _targetApp = ""; _runtime = ""; }
            _reader = new Thread(() => ReadLoop(p)) { IsBackground = true, Name = "PresentMon reader", Priority = ThreadPriority.BelowNormal };
            _reader.Start();
            Log.Info("Frames", (Extended ? $"PresentMon started (latency and frame gen, tier {_tier})" : "PresentMon started")
                + (_staleSession ? ", replacing a leftover session" : ""));
            _staleSession = false;
            return true;
        }
        catch (Exception ex) { Error = "PresentMon didn't start: " + ex.Message; Log.Warn("Frames.Start", ex); _running = false; return false; }
    }

    /// <summary>Stops now: PresentMon is asked to quit and closes its own ETW session; the wait for it runs in the
    /// background (a later Start waits for it). If it doesn't quit in time it is killed, and the next start replaces
    /// the session it left behind.</summary>
    public void Stop() => Stop(wait: false);

    /// <summary>App exit: same as Stop but waits (bounded) so PresentMon closes its session before the job object
    /// would kill it.</summary>
    public void StopAndWait() => Stop(wait: true);

    private void Stop(bool wait) { lock (_life) StopCore(wait); }

    private void StopCore(bool wait)
    {
        CancelStopSoon();
        if (!_running && _proc is null) { if (wait) WaitForStopping(); return; }
        _running = false;
        var p = _proc;
        _proc = null;
        lock (_lock) { _count = 0; _targetPid = 0; _targetApp = ""; _runtime = ""; }
        if (p is not null)
        {
            var t = System.Threading.Tasks.Task.Run(() => Shutdown(p));
            _stopping = t;
            if (wait) t.Wait(3000);
        }
        Log.Info("Frames", "PresentMon stopped");
    }

    private System.Threading.Tasks.Task? _stopping;
    private static volatile bool _staleSession;   // a PresentMon of ours was killed, or one reported our session exists
    private volatile bool _sawStale;

    private void WaitForStopping()
    {
        var t = _stopping;
        if (t is null) return;
        try { t.Wait(3000); } catch { /* logged inside */ }
        _stopping = null;
    }

    /// <summary>Asks PresentMon to quit through its own message window (what its Ctrl+C handler does), then waits.
    /// Kill only as the last resort.</summary>
    private static void Shutdown(Process p)
    {
        try
        {
            if (p.HasExited) return;
            bool asked = false;
            for (int i = 0; i < 10 && !asked && !p.HasExited; i++)   // the window appears right after launch
            {
                asked = PostQuit(p.Id);
                if (!asked) Thread.Sleep(50);
            }
            if (p.WaitForExit(2500)) return;
            Log.Info("Frames", asked ? "PresentMon didn't quit in time, killed" : "PresentMon window not found, killed");
            p.Kill(true);
            _staleSession = true;
        }
        catch (Exception e) { Log.Warn("Frames.Shutdown", e); _staleSession = true; }
        finally { try { p.Dispose(); } catch { /* gone */ } }
    }

    [DllImport("user32.dll", CharSet = CharSet.Unicode)] private static extern IntPtr FindWindowEx(IntPtr parent, IntPtr after, string cls, string? title);
    [DllImport("user32.dll")] private static extern bool PostMessage(IntPtr hWnd, uint msg, IntPtr w, IntPtr l);
    private static readonly IntPtr HWND_MESSAGE = new(-3);
    private const uint WM_QUIT = 0x0012;

    private static bool PostQuit(int pid)
    {
        IntPtr h = IntPtr.Zero;
        while ((h = FindWindowEx(HWND_MESSAGE, h, "PresentMon", null)) != IntPtr.Zero)
        {
            GetWindowThreadProcessId(h, out int owner);
            if (owner == pid) return PostMessage(h, WM_QUIT, IntPtr.Zero, IntPtr.Zero);
        }
        return false;
    }

    // ---------- debounced off ----------

    private Timer? _stopSoon;
    private bool StopPending => _stopSoon is not null;

    /// <summary>Overlay went off: stop after a short grace period, so F4 on / off / on keeps one PresentMon.</summary>
    public void StopSoon(int ms = 2000)
    {
        if (!_running) return;
        lock (_lock)
        {
            if (_stopSoon is not null) return;
            Timer? me = null;
            me = new Timer(_ =>
            {
                lock (_lock) { if (!ReferenceEquals(_stopSoon, me)) return; _stopSoon = null; }   // cancelled by a Start
                me!.Dispose();
                Stop();
            }, null, Timeout.Infinite, Timeout.Infinite);
            _stopSoon = me;
            me.Change(ms, Timeout.Infinite);
        }
    }

    private void CancelStopSoon()
    {
        lock (_lock) { _stopSoon?.Dispose(); _stopSoon = null; }
    }

    // ---------- CSV ----------

    private int _colApp = -1, _colPid = -1, _colRuntime = -1, _colMs = -1, _colT = -1;
    private int _colType = -1, _colPcLat = -1, _colDispLat = -1;

    /// <summary>Reads the header once, then one frame per line. Lines that don't belong to the foreground process are dropped.</summary>
    private void ReadLoop(Process p)
    {
        try
        {
            var reader = p.StandardOutput;
            string? line;
            bool header = false;
            // read to EOF even after Stop, so PresentMon never blocks on a full pipe while it shuts down
            while ((line = reader.ReadLine()) is not null)
            {
                if (!_running || !ReferenceEquals(_proc, p)) continue;
                if (!header)
                {
                    if (!line.StartsWith("Application", StringComparison.OrdinalIgnoreCase)) continue;
                    if (!ParseHeader(line)) { Error = "PresentMon output not understood."; Log.Info("Frames", "header: " + line); return; }
                    header = true;
                    continue;
                }
                OnLine(line);
            }
            if (_running && ReferenceEquals(_proc, p))
            {
                Log.Info("Frames", $"PresentMon exited ({SafeExit(p)})");
                // a session of our name was left behind (an earlier PresentMon was killed): start once more replacing it
                try { p.WaitForExit(500); } catch { /* gone */ }
                if (!header && _sawStale && Stopwatch.GetTimestamp() - _startedAt < Stopwatch.Frequency * 5)
                {
                    _staleSession = true;
                    _running = false;
                    _proc = null;
                    ThreadPool.QueueUserWorkItem(_ => Start());
                    return;
                }
                // extended mode died right away: this build may not know the instrumentation flags, retry without them once
                if (Extended && _tier == 0 && !header && Stopwatch.GetTimestamp() - _startedAt < Stopwatch.Frequency * 5)
                {
                    _tier = 1;
                    _running = false;
                    _proc = null;
                    Log.Info("Frames", "retrying without --track_frame_type / --track_pc_latency");
                    ThreadPool.QueueUserWorkItem(_ => Start());
                    return;
                }
                Error = "PresentMon stopped.";
            }
        }
        catch (Exception ex) { if (_running) { Error = "PresentMon read failed."; Log.Warn("Frames.Read", ex); } }
        finally { if (ReferenceEquals(_proc, p)) _running = false; }   // a retry may already own _proc / _running
    }

    private static string SafeExit(Process p) { try { return p.HasExited ? p.ExitCode.ToString() : "running"; } catch { return "?"; } }

    internal bool ParseHeader(string line)
    {
        var cols = line.Split(',');
        _colApp = _colPid = _colRuntime = _colMs = _colT = -1;
        _colType = _colPcLat = _colDispLat = -1;
        for (int i = 0; i < cols.Length; i++)
        {
            var c = cols[i].Trim();
            if (c.Equals("Application", StringComparison.OrdinalIgnoreCase)) _colApp = i;
            else if (c.Equals("ProcessID", StringComparison.OrdinalIgnoreCase)) _colPid = i;
            else if (c.Equals("PresentRuntime", StringComparison.OrdinalIgnoreCase)) _colRuntime = i;
            else if (c.Equals("MsBetweenPresents", StringComparison.OrdinalIgnoreCase)) _colMs = i;
            else if (_colMs < 0 && c.Equals("FrameTime", StringComparison.OrdinalIgnoreCase)) _colMs = i;
            else if (c.Equals("CPUStartTime", StringComparison.OrdinalIgnoreCase) || c.Equals("TimeInSeconds", StringComparison.OrdinalIgnoreCase)) _colT = i;
            else if (c.Equals("FrameType", StringComparison.OrdinalIgnoreCase)) _colType = i;
            else if (c.Equals("MsPCLatency", StringComparison.OrdinalIgnoreCase)) _colPcLat = i;
            else if (c.Equals("DisplayLatency", StringComparison.OrdinalIgnoreCase) || c.Equals("MsDisplayLatency", StringComparison.OrdinalIgnoreCase)) _colDispLat = i;
        }
        return _colPid >= 0 && _colMs >= 0;
    }

    /// <summary>Parses one CSV line (no allocation for skipped lines beyond the split). Returns true when a frame was kept.</summary>
    internal bool OnLine(string line)
    {
        long now = Stopwatch.GetTimestamp();
        if (now - _lastFgCheck > Stopwatch.Frequency / 4) { _lastFgCheck = now; RefreshForeground(); }
        var cols = line.Split(',');
        if (cols.Length <= Math.Max(_colPid, _colMs)) return false;
        if (!int.TryParse(cols[_colPid], out int pid)) return false;
        int fg;
        lock (_lock) fg = _fgPid;
        if (pid != fg) return false;
        if (!float.TryParse(cols[_colMs], System.Globalization.NumberStyles.Float, System.Globalization.CultureInfo.InvariantCulture, out float ms)) return false;
        if (ms <= 0 || ms > 5000) return false;
        double t = double.NaN;
        if (_colT >= 0 && _colT < cols.Length) double.TryParse(cols[_colT], System.Globalization.NumberStyles.Float, System.Globalization.CultureInfo.InvariantCulture, out t);
        // extended columns (only present when the toggle is on)
        bool gen = _colType >= 0 && _colType < cols.Length && IsGenerated(cols[_colType]);
        float lat = float.NaN; bool pcLat = false;
        if (_colPcLat >= 0 && _colPcLat < cols.Length && TryMs(cols[_colPcLat], out float pl)) { lat = pl; pcLat = true; }
        else if (_colDispLat >= 0 && _colDispLat < cols.Length && TryMs(cols[_colDispLat], out float dl)) lat = dl;
        lock (_lock)
        {
            if (_targetPid != pid)
            {
                _targetPid = pid;
                _targetApp = _colApp >= 0 && _colApp < cols.Length ? cols[_colApp] : "";
                _runtime = _colRuntime >= 0 && _colRuntime < cols.Length ? cols[_colRuntime] : "";
                _count = 0;
            }
            if (double.IsNaN(t)) t = (_count > 0 ? _ring[(_head - 1 + _ring.Length) % _ring.Length].T : 0) + ms / 1000.0;
            _ring[_head] = new Frame(now, t, ms, gen, lat, pcLat);
            _head = (_head + 1) % _ring.Length;
            if (_count < _ring.Length) _count++;
        }
        return true;
    }

    /// <summary>PresentMon's FrameType: Application (rendered by the game), Repeated, NotSet, or the name of whatever
    /// generated it (Intel XeFG, AMD AFMF, ...). Anything that isn't the game's own or a repeat counts as generated.</summary>
    internal static bool IsGenerated(string type)
    {
        var x = type.Trim();
        if (x.Length == 0) return false;
        return !(x.Equals("Application", StringComparison.OrdinalIgnoreCase) || x.Equals("NotSet", StringComparison.OrdinalIgnoreCase)
              || x.Equals("Repeated", StringComparison.OrdinalIgnoreCase) || x.Equals("NA", StringComparison.OrdinalIgnoreCase)
              || x.Equals("Unknown", StringComparison.OrdinalIgnoreCase));
    }

    private static bool TryMs(string s, out float v) =>
        float.TryParse(s, System.Globalization.NumberStyles.Float, System.Globalization.CultureInfo.InvariantCulture, out v) && v > 0 && v < 2000;

    // ---------- foreground process ----------

    [DllImport("user32.dll")] private static extern IntPtr GetForegroundWindow();
    [DllImport("user32.dll")] private static extern uint GetWindowThreadProcessId(IntPtr hWnd, out int pid);
    private int _fgPid;

    private void RefreshForeground()
    {
        var h = GetForegroundWindow();
        int pid = 0;
        if (h != IntPtr.Zero) GetWindowThreadProcessId(h, out pid);
        lock (_lock) _fgPid = pid;
    }

    /// <summary>Test hook: pretend this pid owns the foreground window.</summary>
    internal void SetForegroundForTest(int pid) { lock (_lock) _fgPid = pid; _lastFgCheck = long.MaxValue / 2; }

    // ---------- stats for the overlay ----------

    /// <summary>Copies the newest frames (oldest first) into dst; returns how many. Used by the overlay thread.</summary>
    public int CopyRecent(Span<Frame> dst)
    {
        lock (_lock)
        {
            int n = Math.Min(dst.Length, _count);
            int start = (_head - n + _ring.Length) % _ring.Length;
            for (int i = 0; i < n; i++) dst[i] = _ring[(start + i) % _ring.Length];
            return n;
        }
    }

    /// <summary>MangoHud's fps: the frames of the last sampling period, measured on PresentMon's own clock (the newest
    /// frame's CPUStartTime back by the window), so bursty stdout doesn't skew it. Zero once nothing new has
    /// arrived for a second (game paused, alt tabbed).</summary>
    public static (double Fps, double AvgMs) FpsOver(ReadOnlySpan<Frame> frames, long nowTicks, long windowTicks)
    {
        if (frames.Length == 0) return (0, 0);
        if (nowTicks - frames[^1].Ticks > Stopwatch.Frequency) return (0, 0);
        double window = windowTicks / (double)Stopwatch.Frequency, last = frames[^1].T;
        double sum = 0; int n = 0;
        for (int i = frames.Length - 1; i >= 0; i--)
        {
            if (last - frames[i].T > window) break;
            sum += frames[i].Ms; n++;
        }
        if (n == 0) return (0, 0);
        double avg = sum / n;
        return (avg > 0 ? 1000.0 / avg : 0, avg);
    }

    /// <summary>Real / generated fps and latency over the same window as FpsOver. Real = the share of the game's own
    /// frames; with no generated frames seen, real = all frames (what level 1 shows).</summary>
    public static Stats StatsOver(ReadOnlySpan<Frame> frames, long nowTicks, long windowTicks)
    {
        var (fps, avg) = FpsOver(frames, nowTicks, windowTicks);
        if (fps <= 0) return new Stats(0, 0, 0, double.NaN, false);
        double window = windowTicks / (double)Stopwatch.Frequency, last = frames[^1].T;
        int n = 0, gen = 0, latN = 0, pcN = 0; double latSum = 0, pcSum = 0;
        for (int i = frames.Length - 1; i >= 0; i--)
        {
            var f = frames[i];
            if (last - f.T > window) break;
            n++;
            if (f.Gen) gen++;
            if (float.IsNaN(f.Lat) || f.Gen) continue;
            if (f.PcLat) { pcSum += f.Lat; pcN++; } else { latSum += f.Lat; latN++; }
        }
        double genFps = n > 0 ? fps * gen / n : 0;
        // Reflex PC latency wins when the game sends it; otherwise PresentMon's display latency
        double lat = pcN > 0 ? pcSum / pcN : latN > 0 ? latSum / latN : double.NaN;
        return new Stats(fps - genFps, genFps, avg, lat, pcN > 0);
    }

    // ---------- job object: PresentMon dies with us ----------

    [DllImport("kernel32.dll", CharSet = CharSet.Unicode)] private static extern IntPtr CreateJobObject(IntPtr a, string? name);
    [DllImport("kernel32.dll")] private static extern bool SetInformationJobObject(IntPtr job, int cls, ref JOBOBJECT_EXTENDED_LIMIT_INFORMATION info, int len);
    [DllImport("kernel32.dll")] private static extern bool AssignProcessToJobObject(IntPtr job, IntPtr process);

    [StructLayout(LayoutKind.Sequential)]
    private struct JOBOBJECT_BASIC_LIMIT_INFORMATION
    {
        public long PerProcessUserTimeLimit, PerJobUserTimeLimit;
        public uint LimitFlags;
        public UIntPtr MinimumWorkingSetSize, MaximumWorkingSetSize;
        public uint ActiveProcessLimit;
        public UIntPtr Affinity;
        public uint PriorityClass, SchedulingClass;
    }
    [StructLayout(LayoutKind.Sequential)]
    private struct IO_COUNTERS { public ulong a, b, c, d, e, f; }
    [StructLayout(LayoutKind.Sequential)]
    private struct JOBOBJECT_EXTENDED_LIMIT_INFORMATION
    {
        public JOBOBJECT_BASIC_LIMIT_INFORMATION Basic;
        public IO_COUNTERS Io;
        public UIntPtr ProcessMemoryLimit, JobMemoryLimit, PeakProcessMemoryUsed, PeakJobMemoryUsed;
    }

    private void AttachToJob(Process p)
    {
        try
        {
            if (_job == IntPtr.Zero)
            {
                _job = CreateJobObject(IntPtr.Zero, null);
                var info = new JOBOBJECT_EXTENDED_LIMIT_INFORMATION();
                info.Basic.LimitFlags = 0x2000;   // JOB_OBJECT_LIMIT_KILL_ON_JOB_CLOSE
                SetInformationJobObject(_job, 9, ref info, Marshal.SizeOf<JOBOBJECT_EXTENDED_LIMIT_INFORMATION>());
            }
            AssignProcessToJobObject(_job, p.Handle);
        }
        catch (Exception e) { Log.Warn("Frames.Job", e); }
    }

    public void Dispose() => Stop();
}
