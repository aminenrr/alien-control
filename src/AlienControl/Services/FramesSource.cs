    private readonly object _life = new();

    public bool Start() { lock (_life) return StartCore(); }

    private bool StartCore()
    {
        CancelStopSoon();
        if (_running) return true;
        WaitForStopping();
        Error = null;
        if (!Available) { Error = "PresentMon is missing (tools\\PresentMon)."; Log.Info("Frames", Error); return false; }
        try
        {
            _sawStale = false;
            // diag (Amine 2026-10-26): QPC timestamps and ETW status columns, only when overlay-diag.json turns it on
            var args = Args(Extended, _tier, _staleSession, TrackGpu)
                + (OverlayDiag.On ? " --qpc_time" + (OverlayDiag.Cfg.EtwStatus ? " --track_etw_status" : "") : "");
            var exe = RunPath();
            if (OverlayDiag.On && exe != ExePath) OverlayDiag.StartDrain();
            var psi = new ProcessStartInfo(exe, args)
            {
                CreateNoWindow = true, UseShellExecute = false, RedirectStandardOutput = true, RedirectStandardError = true,
                WorkingDirectory = Path.GetDirectoryName(exe)!,
            };
            var p = Process.Start(psi)!;
            AttachToJob(p);
            p.ErrorDataReceived += (_, e) =>
            {
                if (string.IsNullOrWhiteSpace(e.Data)) return;
                Log.Info("PresentMon", e.Data!);
                if (e.Data!.Contains("already running", StringComparison.OrdinalIgnoreCase)) _sawStale = true;
            };
            p.BeginErrorReadLine();
            _proc = p;
            _running = true;
            _startedAt = Stopwatch.GetTimestamp();
            lock (_lock) { _head = 0; _count = 0; _targetPid = 0; _targetApp = ""; _runtime = ""; _presentMode = ""; _syncInterval = -1; }
            // diag pass 2: with overlay-diag.json the raw pipe is read by a Highest-priority pump that stamps each chunk,
            // and the reader parses lines behind it (W_k). Without diag this is p.StandardOutput, as in 2.0.2.
            OverlayDiag.Pump? pump = OverlayDiag.On && OverlayDiag.Cfg.Pump ? OverlayDiag.Pump.Start(p.StandardOutput.BaseStream, "diag stdout pump") : null;
            TextReader rd = pump is null ? p.StandardOutput : new StreamReader(pump, p.StandardOutput.CurrentEncoding, false, 4096);
            _reader = new Thread(() => ReadLoop(p, rd, pump)) { IsBackground = true, Name = "PresentMon reader",
                Priority = OverlayDiag.On ? OverlayDiag.ReaderPriority() : ThreadPriority.BelowNormal };
            _reader.Start();
            if (OverlayDiag.On)
            {
                OverlayDiag.PresentMonCpu = () => { try { return p.HasExited ? TimeSpan.Zero : p.TotalProcessorTime; } catch { return TimeSpan.Zero; } };
                OverlayDiag.StartEtwControl(SessionName, () => _running && _proc is not null);
                Log.Info("Diag", $"PresentMon exe: {Path.GetFileName(exe)}; args: {args}; reader priority {_reader.Priority}; pump {(pump is not null)}");
            }
            Log.Info("Frames", (Extended ? $"PresentMon started (latency and frame gen, tier {_tier})" : "PresentMon started") + (TrackGpu ? ", GPU tracking" : "")
                + (_staleSession ? ", replacing a leftover session" : ""));
            _staleSession = false;
            return true;
        }
        catch (Exception ex) { Error = "PresentMon didn't start: " + ex.Message; Log.Warn("Frames.Start", ex); _running = false; return false; }
    }

    /// <summary>Stops now: PresentMon is asked to quit and closes its own ETW session; the wait for it runs in the
    /// background (a later Start waits for it). If it doesn't quit in time it is killed, and the next start replaces
    /// the session it left behind.</summary>
    public void Stop() => Stop(wait: false);

    /// <summary>App exit: same as Stop but waits (bounded) so PresentMon closes its session before the job object
    /// would kill it.</summary>
    public void StopAndWait() => Stop(wait: true);

    private void Stop(bool wait) { lock (_life) StopCore(wait); }

    private void StopCore(bool wait)
    {
        CancelStopSoon();
        if (!_running && _proc is null) { if (wait) WaitForStopping(); return; }
        _running = false;
        var p = _proc;
        _proc = null;
        lock (_lock) { _count = 0; _targetPid = 0; _targetApp = ""; _runtime = ""; _presentMode = ""; }
        if (p is not null)
        {
            var t = System.Threading.Tasks.Task.Run(() => Shutdown(p));
            _stopping = t;
            if (wait) t.Wait(3000);
        }
        Log.Info("Frames", "PresentMon stopped");
    }

    private System.Threading.Tasks.Task? _stopping;
    private static volatile bool _staleSession;   // a PresentMon of ours was killed, or one reported our session exists
    private volatile bool _sawStale;

    private void WaitForStopping()
    {
        var t = _stopping;
        if (t is null) return;
        try { t.Wait(3000); } catch { /* logged inside */ }
        _stopping = null;
    }

    /// <summary>Asks PresentMon to quit through its own message window (what its Ctrl+C handler does), then waits.
    /// Kill only as the last resort.</summary>
    private static void Shutdown(Process p)
    {
        try
        {
            if (p.HasExited) return;
            bool asked = false;
            for (int i = 0; i < 10 && !asked && !p.HasExited; i++)   // the window appears right after launch
            {
                asked = PostQuit(p.Id);
                if (!asked) Thread.Sleep(50);
            }
            if (p.WaitForExit(2500)) return;
            Log.Info("Frames", asked ? "PresentMon didn't quit in time, killed" : "PresentMon window not found, killed");
            p.Kill(true);
            _staleSession = true;
        }
        catch (Exception e) { Log.Warn("Frames.Shutdown", e); _staleSession = true; }
        finally { try { p.Dispose(); } catch { /* gone */ } }
    }

    [DllImport("user32.dll", CharSet = CharSet.Unicode)] private static extern IntPtr FindWindowEx(IntPtr parent, IntPtr after, string cls, string? title);
    [DllImport("user32.dll")] private static extern bool PostMessage(IntPtr hWnd, uint msg, IntPtr w, IntPtr l);
    private static readonly IntPtr HWND_MESSAGE = new(-3);
    private const uint WM_QUIT = 0x0012;

    private static bool PostQuit(int pid)
    {
        IntPtr h = IntPtr.Zero;
        while ((h = FindWindowEx(HWND_MESSAGE, h, "PresentMon", null)) != IntPtr.Zero)
        {
            GetWindowThreadProcessId(h, out int owner);
            if (owner == pid) return PostMessage(h, WM_QUIT, IntPtr.Zero, IntPtr.Zero);
        }
        return false;
    }

    // ---------- debounced off ----------

    private Timer? _stopSoon;
    private bool StopPending => _stopSoon is not null;

    /// <summary>Overlay went off: stop after a short grace period, so F4 on / off / on keeps one PresentMon.</summary>
    public void StopSoon(int ms = 2000)
    {
        if (!_running) return;
        lock (_lock)
        {
            if (_stopSoon is not null) return;
            Timer? me = null;
            me = new Timer(_ =>
            {
                lock (_lock) { if (!ReferenceEquals(_stopSoon, me)) return; _stopSoon = null; }   // cancelled by a Start
                me!.Dispose();
                Stop();
            }, null, Timeout.Infinite, Timeout.Infinite);
            _stopSoon = me;
            me.Change(ms, Timeout.Infinite);
        }
    }

    private void CancelStopSoon()
    {
        lock (_lock) { _stopSoon?.Dispose(); _stopSoon = null; }
    }

    // ---------- CSV ----------

    private int _colApp = -1, _colPid = -1, _colRuntime = -1, _colMs = -1, _colT = -1;
    private int _colType = -1, _colPcLat = -1, _colDispLat = -1, _colMode = -1, _colSwap = -1, _colMax = -1;
    private int _colGpuBusy = -1, _colSync = -1, _colDispChange = -1;   // ov.15; beta2.3 display change

    /// <summary>Reads the header once, then one frame per line. Lines that don't belong to the foreground process are dropped.</summary>
    private void ReadLoop(Process p, TextReader reader, OverlayDiag.Pump? pump)
    {
        try
        {
            string? line;
            bool header = false;
            // read to EOF even after Stop, so PresentMon never blocks on a full pipe while it shuts down
            while ((line = reader.ReadLine()) is not null)
            {
                if (!_running || !ReferenceEquals(_proc, p)) continue;
                // diag pass 2: --track_etw_status lines ("[ETW Status] ...") are interleaved with the CSV; not rows
                if (OverlayDiag.On && line.Length > 0 && line[0] == '[' && OverlayDiag.OnEtwStatusLine(Stopwatch.GetTimestamp(), line)) continue;
                if (!header)
                {
                    if (!line.StartsWith("Application", StringComparison.OrdinalIgnoreCase)) continue;
                    if (!ParseHeader(line)) { Error = "PresentMon output not understood."; Log.Info("Frames", "header: " + line); return; }
                    header = true;
                    continue;
                }
                if (OverlayDiag.On) OverlayDiag.OnRow(Stopwatch.GetTimestamp(), line.Length + 2, pump?.LastQpc ?? 0, pump?.LastSeq ?? 0);
                OnLine(line);
            }
            if (_running && ReferenceEquals(_proc, p))
            {
                Log.Info("Frames", $"PresentMon exited ({SafeExit(p)})");
                // a session of our name was left behind (an earlier PresentMon was killed): start once more replacing it
                try { p.WaitForExit(500); } catch { /* gone */ }
                if (!header && _sawStale && Stopwatch.GetTimestamp() - _startedAt < Stopwatch.Frequency * 5)
                {
                    _staleSession = true;
                    _running = false;
                    _proc = null;
                    ThreadPool.QueueUserWorkItem(_ => Start());
                    return;
                }
                // extended mode died right away: this build may not know the instrumentation flags, retry without them once
                if (_tier == 0 && !header && Stopwatch.GetTimestamp() - _startedAt < Stopwatch.Frequency * 5)
                {
                    _tier = 1;
                    _running = false;
                    _proc = null;
                    Log.Info("Frames", "retrying without --track_frame_type / --track_pc_latency");
                    ThreadPool.QueueUserWorkItem(_ => Start());
                    return;
                }
                Error = "PresentMon stopped.";
            }
        }
        catch (Exception ex) { if (_running) { Error = "PresentMon read failed."; Log.Warn("Frames.Read", ex); } }
        finally { if (ReferenceEquals(_proc, p)) _running = false; }   // a retry may already own _proc / _running
    }

    private static string SafeExit(Process p) { try { return p.HasExited ? p.ExitCode.ToString() : "running"; } catch { return "?"; } }

    internal bool ParseHeader(string line)
    {
        var cols = line.Split(',');
        _colApp = _colPid = _colRuntime = _colMs = _colT = -1;
        _colType = _colPcLat = _colDispLat = _colMode = _colSwap = -1;
        _colGpuBusy = _colSync = _colUntil = _colDispChange = -1;
        _colPq = _colEtw = -1; _tQpc = false;
        // beta2 (Amine: LATENCY showed --): the columns this PresentMon sends, once per start
        Log.Info("Frames", "columns: " + line);
        int tRank = 0; _tScale = 1.0;
        for (int i = 0; i < cols.Length; i++)
        {
            var c = cols[i].Trim();
            if (c.Equals("Application", StringComparison.OrdinalIgnoreCase)) _colApp = i;
            else if (c.Equals("ProcessID", StringComparison.OrdinalIgnoreCase)) _colPid = i;
            else if (c.Equals("PresentRuntime", StringComparison.OrdinalIgnoreCase)) _colRuntime = i;
            else if (c.Equals("MsBetweenPresents", StringComparison.OrdinalIgnoreCase)) _colMs = i;
            else if (_colMs < 0 && c.Equals("FrameTime", StringComparison.OrdinalIgnoreCase)) _colMs = i;
            // beta2.1 (Amine: 0 FPS, dead graph): with --track_frame_type PresentMon 2.6 prints the time in ms
            // (CPUStartTimeInMs / TimeInMs). Best first: CPUStartTime, CPUStartTimeInMs, TimeInSeconds, TimeInMs.
            else if (TimeRank(c) is int r && r > tRank) { _colT = i; tRank = r; _tScale = r == 5 ? 1.0 / Stopwatch.Frequency : r is 4 or 2 ? 1.0 : 0.001; _tQpc = r == 5; }
            // diag: the Present() call time in QPC and the first ETW status column (--track_etw_status)
            else if (c.Equals("TimeInQPC", StringComparison.OrdinalIgnoreCase)) _colPq = i;
            else if (c.Equals("EtwBufferFillPct", StringComparison.OrdinalIgnoreCase)) _colEtw = i;
            else if (c.Equals("FrameType", StringComparison.OrdinalIgnoreCase)) _colType = i;
            else if (c.Equals("PresentMode", StringComparison.OrdinalIgnoreCase)) _colMode = i;
            else if (c.Equals("MsPCLatency", StringComparison.OrdinalIgnoreCase)) _colPcLat = i;
            else if (c.Equals("DisplayLatency", StringComparison.OrdinalIgnoreCase) || c.Equals("MsDisplayLatency", StringComparison.OrdinalIgnoreCase)) _colDispLat = i;
            else if (c.Equals("SwapChainAddress", StringComparison.OrdinalIgnoreCase)) _colSwap = i;
            // ov.15: GPU busy (PresentMon 2: MsGPUBusy; 1.x: MsGPUActive) and the game's V-Sync
            else if (c.Equals("MsGPUBusy", StringComparison.OrdinalIgnoreCase) || c.Equals("GPUBusy", StringComparison.OrdinalIgnoreCase)) _colGpuBusy = i;
            else if (_colGpuBusy < 0 && c.Equals("MsGPUActive", StringComparison.OrdinalIgnoreCase)) _colGpuBusy = i;
            else if (c.Equals("SyncInterval", StringComparison.OrdinalIgnoreCase)) _colSync = i;
            // beta2.3 (Amine: FG graph zigzag 0.3 / 14 ms): time between frames reaching the screen (latency toggle on)
            else if (c.Equals("MsBetweenDisplayChange", StringComparison.OrdinalIgnoreCase)) _colDispChange = i;
            // beta2: display latency under its other names, and the time until display as the last fallback
            else if (_colDispLat < 0 && (c.Equals("MsDisplayLatency", StringComparison.OrdinalIgnoreCase) || c.Equals("MsDisplayedLatency", StringComparison.OrdinalIgnoreCase))) _colDispLat = i;
            else if (c.Equals("MsUntilDisplayed", StringComparison.OrdinalIgnoreCase) || c.Equals("UntilDisplayed", StringComparison.OrdinalIgnoreCase)) _colUntil = i;
        }
        _colMax = Math.Max(Math.Max(Math.Max(_colApp, _colPid), Math.Max(_colRuntime, _colMs)), Math.Max(Math.Max(_colT, _colType),
                  Math.Max(Math.Max(_colPcLat, _colDispLat), Math.Max(_colMode, _colSwap))));
        _colMax = Math.Max(_colMax, Math.Max(Math.Max(_colGpuBusy, _colSync), Math.Max(_colUntil, _colDispChange)));
        if (_colPq >= 0) _colMax = Math.Max(_colMax, _colPq);
        if (_colEtw >= 0) _colMax = Math.Max(_colMax, _colEtw + 5);
        _starts = new int[_colMax + 2];
        if (_colT < 0) Log.Info("Frames", "no time column, using arrival time");
        return _colPid >= 0 && _colMs >= 0;
    }

    /// <summary>beta2.1: rank of a time column (0 = not one). Higher wins.</summary>
    private static int TimeRank(string c) =>
        c.Equals("CPUStartQPC", StringComparison.OrdinalIgnoreCase) ? 5 :   // diag: --qpc_time (QPC ticks, Stopwatch's clock)
        c.Equals("CPUStartTime", StringComparison.OrdinalIgnoreCase) ? 4 :
        c.Equals("CPUStartTimeInMs", StringComparison.OrdinalIgnoreCase) ? 3 :
        c.Equals("TimeInSeconds", StringComparison.OrdinalIgnoreCase) ? 2 :
        c.Equals("TimeInMs", StringComparison.OrdinalIgnoreCase) ? 1 : 0;

    private double _tScale = 1.0;   // beta2.1: seconds per unit of the time column
    private int _colPq = -1, _colEtw = -1;   // diag
    private bool _tQpc;
    private int _etwEvery;

    private int[] _starts = new int[2];
    private int _colUntil = -1;

    // ov.11 swapchain filter: a game can present on more than one swapchain (launcher overlay, a video in a menu, a
    // second window). Mixing them inflated the fps and jumbled the frametimes, so only the busiest one counts.
    private readonly ulong[] _swAddr = new ulong[4];
    private readonly int[] _swCount = new int[4];
    private ulong _swPrimary;
    private long _swPicked;

    /// <summary>Parses one CSV line without allocating (the columns are spans of the line; strings are only made when
    /// the target or its present mode changes). Returns true when a frame was kept.</summary>
    internal bool OnLine(string line)
    {
        long now = Stopwatch.GetTimestamp();
        if (now - _lastFgCheck > Stopwatch.Frequency / 4) { _lastFgCheck = now; RefreshForeground(); }
        var span = line.AsSpan();
        int n = Split(span, _starts);
        if (n <= Math.Max(_colPid, _colMs)) return false;
        if (!int.TryParse(Col(span, _colPid, n), out int pid)) return false;
        int fg;
        lock (_lock) fg = _fgPid;
        if (pid != fg) return false;
        var inv = System.Globalization.CultureInfo.InvariantCulture;
        var flt = System.Globalization.NumberStyles.Float;
        if (!float.TryParse(Col(span, _colMs, n), flt, inv, out float ms)) return false;
        if (ms <= 0 || ms > 5000) return false;
        if (!PrimarySwapchain(Col(span, _colSwap, n), pid, now)) return false;
        // beta2.3: with display tracking (latency toggle on) the frametime is what reached the screen, like PresentMon's
        // own overlay: frame gen presents its pair back to back (0.3 / 14 ms) and the driver paces them later, so
        // MsBetweenPresents zigzags while the screen gets even frames. Frames that never reached the screen are dropped.
        // beta2.5: undisplayed frames are kept (hidden) so the fps still counts every present like RTSS / Steam
        float presentMs = ms; bool hidden = false;
        if (_colDispChange >= 0)
        {
            if (_colDispChange < n && float.TryParse(Col(span, _colDispChange, n), flt, inv, out float dc) && dc > 0 && dc <= 5000) ms = dc;
            else hidden = true;
        }
        double t = double.NaN;
        if (_colT >= 0 && _colT < n && double.TryParse(Col(span, _colT, n), flt, inv, out double tv)) t = tv * _tScale;
        if (_colT < 0) t = now / (double)Stopwatch.Frequency;   // beta2.1: no time column, arrival time beats no time at all
        long pq = 0, cq = 0;
        if (OverlayDiag.On)
        {
            if (_colPq >= 0 && _colPq < n) long.TryParse(Col(span, _colPq, n), out pq);
            if (_tQpc && _colT < n) long.TryParse(Col(span, _colT, n), out cq);
            OverlayDiag.OnFrame(now, cq, pq, ms);
            if (_colEtw >= 0 && _colEtw + 5 < n && ++_etwEvery % 100 == 0)
                OverlayDiag.OnEtwStatus(Col(span, _colEtw, n).ToString(), Col(span, _colEtw + 1, n).ToString(), Col(span, _colEtw + 2, n).ToString(),
                    Col(span, _colEtw + 3, n).ToString(), Col(span, _colEtw + 4, n).ToString(), Col(span, _colEtw + 5, n).ToString());
        }
        // extended columns (only present when the toggle is on)
        bool gen = _colType >= 0 && _colType < n && IsGenerated(Col(span, _colType, n));
        // beta2.2 (Amine: show fps like RTSS): no guessing; generated frames only count for the FG tile
        float lat = float.NaN; bool pcLat = false, changed = false;
        string app = "";
        if (_colPcLat >= 0 && _colPcLat < n && TryMs(Col(span, _colPcLat, n), out float pl)) { lat = pl; pcLat = true; }
        else if (_colDispLat >= 0 && _colDispLat < n && TryMs(Col(span, _colDispLat, n), out float dl)) lat = dl;
        else if (_colUntil >= 0 && _colUntil < n && TryMs(Col(span, _colUntil, n), out float ud)) lat = ud;   // beta2
        float gpuBusy = float.NaN;
        if (_colGpuBusy >= 0 && _colGpuBusy < n && float.TryParse(Col(span, _colGpuBusy, n), flt, inv, out float gb) && gb >= 0 && gb < 5000) gpuBusy = gb;
        int sync = -1;
        if (_colSync >= 0 && _colSync < n && !gen && int.TryParse(Col(span, _colSync, n), out int si)) sync = si;
        lock (_lock)
        {
            if (_targetPid != pid)
            {
                _targetPid = pid;
                _targetApp = _colApp >= 0 && _colApp < n ? Col(span, _colApp, n).ToString() : "";
                _runtime = _colRuntime >= 0 && _colRuntime < n ? Col(span, _colRuntime, n).ToString() : "";
                _count = 0;
                changed = true;
                app = _targetApp;
                if (OverlayDiag.On) OverlayDiag.Target = _targetApp;
            }
            if (_colMode >= 0 && _colMode < n && !gen)   // the game's own frames
            {
                var mode = Col(span, _colMode, n);
                if (!mode.SequenceEqual(_presentMode.AsSpan())) _presentMode = mode.ToString();
            }
            if (double.IsNaN(t)) t = (_count > 0 ? _ring[(_head - 1 + _ring.Length) % _ring.Length].T : 0) + ms / 1000.0;
            // beta2: a real frame after generated ones gets the time since the last real frame (its true frametime)
            if (sync >= 0) _syncInterval = sync;
            _ring[_head] = new Frame(now, t, ms, gen, lat, pcLat, gpuBusy, presentMs, hidden, pq);
            _head = (_head + 1) % _ring.Length;
            if (_count < _ring.Length) _count++;
        }
        if (changed) { try { TargetChanged?.Invoke(app, pid); } catch (Exception e) { Log.Warn("Frames.TargetChanged", e); } }
        return true;
    }

    /// <summary>Comma positions of the line into starts (starts[i] = first char of column i, starts[n] = end + 1).
    /// Stops after the last column we read. Returns the number of columns found.</summary>
    private int Split(ReadOnlySpan<char> s, int[] starts)
    {
        int max = starts.Length - 1, n = 0, pos = 0;
        starts[0] = 0;
        while (n < max)
        {
            int c = s[pos..].IndexOf(',');
            n++;
            if (c < 0) { starts[n] = s.Length + 1; break; }
            pos += c + 1;
            starts[n] = pos;
        }
        return n;
    }

    private ReadOnlySpan<char> Col(ReadOnlySpan<char> s, int col, int n)
    {
        if (col < 0 || col >= n) return ReadOnlySpan<char>.Empty;
        int a = _starts[col], b = Math.Min(_starts[col + 1] - 1, s.Length);
        return b > a ? s[a..b].Trim() : ReadOnlySpan<char>.Empty;
    }

    /// <summary>Counts presents per swapchain of the target and keeps only the busiest one (re-picked twice a second,
    /// counts halve each time so a switch of window is followed within a second). No column = no filter.</summary>
    private bool PrimarySwapchain(ReadOnlySpan<char> col, int pid, long now)
    {
        if (col.IsEmpty) return true;
        if (col.StartsWith("0x", StringComparison.OrdinalIgnoreCase)) col = col[2..];
        if (!ulong.TryParse(col, System.Globalization.NumberStyles.HexNumber, null, out ulong addr) || addr == 0) return true;
        if (pid != _targetPid) { Array.Clear(_swAddr); Array.Clear(_swCount); _swPrimary = 0; }
        int slot = -1, empty = -1, least = 0;
        for (int i = 0; i < _swAddr.Length; i++)
        {
            if (_swAddr[i] == addr) { slot = i; break; }
            if (_swAddr[i] == 0 && empty < 0) empty = i;
            if (_swCount[i] < _swCount[least]) least = i;
        }
        if (slot < 0) { slot = empty >= 0 ? empty : least; _swAddr[slot] = addr; _swCount[slot] = 0; }
        _swCount[slot]++;
        if (_swPrimary == 0) { _swPrimary = addr; _swPicked = now; }
        else if (now - _swPicked > Stopwatch.Frequency / 2)
        {
            int best = 0;
            for (int i = 1; i < _swAddr.Length; i++) if (_swCount[i] > _swCount[best]) best = i;
            _swPrimary = _swAddr[best];
            for (int i = 0; i < _swCount.Length; i++) _swCount[i] /= 2;
            _swPicked = now;
        }
        return addr == _swPrimary;
    }

    /// <summary>PresentMon's FrameType: Application (rendered by the game), Repeated, NotSet, or the name of whatever
    /// generated it (Intel XeFG, AMD AFMF, ...). Anything that isn't the game's own or a repeat counts as generated.</summary>
    internal static bool IsGenerated(string type) => IsGenerated(type.AsSpan());

    internal static bool IsGenerated(ReadOnlySpan<char> type)
    {
        // beta2.1 (Amine: 0 FPS in Castlevania, no frame gen there): PresentMon 2.6 prints types this list didn't
        // know (Unspecified), and every unknown type counted as generated, so no real frames were left. Now only
        // the frame gen types count: Intel XeFG, AMD AFMF, and anything naming FG / frame generation.
        var x = type.Trim();
        if (x.Length == 0) return false;
        return x.Contains("FG", StringComparison.OrdinalIgnoreCase) || x.Contains("AFMF", StringComparison.OrdinalIgnoreCase)
            || x.Contains("DLSSG", StringComparison.OrdinalIgnoreCase) || x.Contains("Generat", StringComparison.OrdinalIgnoreCase) || x.Contains("Interpol", StringComparison.OrdinalIgnoreCase);
    }

    private static bool TryMs(ReadOnlySpan<char> s, out float v) =>
        float.TryParse(s, System.Globalization.NumberStyles.Float, System.Globalization.CultureInfo.InvariantCulture, out v) && v > 0 && v < 2000;

