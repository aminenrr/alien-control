    public bool Running => _running;

    /// <summary>Latency and frame gen mode (Amine's hard toggle, off by default). On: PresentMon also tracks the display,
    /// the frame type and PC latency. Off: none of that is collected. Changing it restarts a running session.</summary>
    public bool Extended { get; private set; }

    public void SetExtended(bool on)
    {
        if (on == Extended) return;
        Extended = on;
        _tier = 0;
        if (_running && !StopPending) { Stop(); Start(); }
        else if (_running) Stop();   // was about to go off anyway: next Start uses the new mode
    }

    /// <summary>PresentMon command line for a mode. Off = the lean set (no display, GPU or input tracking).
    /// Extended keeps GPU and input off and adds display, frame type and PC latency; tier 1 drops the two
    /// instrumentation flags (fallback if this PresentMon build rejects them).</summary>
    internal static string Args(bool extended, int tier = 0, bool stopExisting = false, bool trackGpu = false)
    {
        // ov.15: GPU tracking (GPU busy per frame) only while the BOUND row is shown
        var a = $"--output_stdout --no_console_stats --session_name {SessionName} " + (stopExisting ? "--stop_existing_session " : "") +
                (trackGpu ? "" : "--no_track_gpu ") + "--no_track_input --set_circular_buffer_size 8192 --exclude dwm.exe --exclude AlienControl.exe";
        // beta2 (Amine: FG games drew a zigzag): the frame type is read in lean mode too, so frame gen is told apart
        // beta2.2 (Amine: still 0 FPS / broken graph): frame type tracking without display tracking made PresentMon hold
        // presents until its buffer overflowed (thousands dropped per run), so frames came out seconds late. Lean
        // mode is back to ov.14's set, the one that worked.
        if (!extended) return a + " --no_track_display";
        return tier == 0 ? a + " --track_frame_type --track_pc_latency" : a;
    }

    /// <summary>ov.15: GPU tracking for the BOUND row (off by default). Changing it restarts a running session.</summary>
    public bool TrackGpu { get; private set; }

