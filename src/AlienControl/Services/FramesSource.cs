/// <summary>
/// beta1.3-ov: frametimes of the foreground game from PresentMon (GameTechDev, MIT), the same ETW data RTSS-free tools
/// use. PresentMon runs as a separate process (tools\PresentMon\PresentMon.exe, no injection, anti cheat safe) and
/// writes one CSV line per Present() to stdout. Only the cheapest tracking is on (no display, GPU or input tracking),
/// since the overlay only needs MsBetweenPresents, the frametime MangoHud shows.
///
/// Lifecycle: Start when the overlay goes from off to a level, Stop when it goes off. Nothing runs while off.
/// The child is put in a kill-on-close job object, so it dies with the app even on a crash or a Task Manager kill,
/// ov.4 (Defender flagged ov.3 as Behavior:Win32/DefenseEvasion.A!ml): we never stop an ETW session ourselves any more.
/// Stop asks PresentMon to quit the way its own Ctrl+C handler does (WM_QUIT to its "PresentMon" message window), so
/// PresentMon closes its own session. No second PresentMon with --terminate_existing_session, and --stop_existing_session
/// is passed only after PresentMon reported a leftover session of our name (it was killed: crash, Task Manager).
/// Going off is debounced (StopSoon), so flipping F4 or the toggle doesn't churn processes.
/// </summary>
public sealed class FramesSource : IDisposable
{
    public const string SessionName = "AlienControlsOverlay";

    /// <summary>One frame: when it arrived (Stopwatch ticks), PresentMon's own CPUStartTime in seconds (exact even when
    /// stdout arrives in bursts) and its frametime in ms. Gen and Lat are only filled in extended mode: Gen = the frame
    /// was generated by a driver / SDK (frame generation), Lat = latency in ms (NaN when unknown), PcLat = Lat is the
    /// Reflex style PC latency (input to display) rather than PresentMon's display latency (frame start to display).</summary>
    public readonly record struct Frame(long Ticks, double T, float Ms, bool Gen = false, float Lat = float.NaN, bool PcLat = false,
        float GpuBusy = float.NaN,   // ov.15: PresentMon's MsGPUBusy, only with GPU tracking (the BOUND row)
        float PresentMs = float.NaN, bool Hidden = false,
        long Pq = 0);   // diag: PresentMon TimeInQPC (the game's Present() call), only with --qpc_time (overlay-diag.json)   // beta2.5: MsBetweenPresents (the fps, like RTSS) and "never reached the screen" (graph / lows skip it)

    /// <summary>The window's stats: real fps (app rendered frames), generated fps (frame generation), average frametime of
    /// all presents, and latency (NaN when none).</summary>
    public readonly record struct Stats(double Fps, double GenFps, double AvgMs, double LatMs, bool PcLat);

