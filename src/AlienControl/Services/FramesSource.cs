        }
    }

    /// <summary>MangoHud's fps: the frames of the last sampling period, measured on PresentMon's own clock (the newest
    /// frame's CPUStartTime back by the window), so bursty stdout doesn't skew it. Zero once nothing new has
    /// arrived for a second (game paused, alt tabbed).</summary>
    public static (double Fps, double AvgMs) FpsOver(ReadOnlySpan<Frame> frames, long nowTicks, long windowTicks)
    {
        if (frames.Length == 0) return (0, 0);
        // ov.14: 1.5 s, PresentMon hands frames over in ETW bursts (up to ~1 s apart), so 1 s flickered to 0
        if (nowTicks - frames[^1].Ticks > Stopwatch.Frequency * 3 / 2) return (0, 0);
        double window = windowTicks / (double)Stopwatch.Frequency, last = frames[^1].T;
        double sum = 0; int n = 0;
        for (int i = frames.Length - 1; i >= 0; i--)
        {
            if (last - frames[i].T > window) break;
            // beta2.2 (Amine): every presented frame counts, like RTSS (beta2 counted real frames only)
            // beta2.5: presents, not display changes (with FG the display side ran ~120 while RTSS / Steam said 140)
            var f = frames[i];
            sum += float.IsNaN(f.PresentMs) ? f.Ms : f.PresentMs; n++;
        }
        if (n == 0) return (0, 0);
        double avg = sum / n;
        return (avg > 0 ? 1000.0 / avg : 0, avg);
    }

    /// <summary>Real / generated fps and latency over the same window as FpsOver. Real = the share of the game's own
    /// frames; with no generated frames seen, real = all frames (what level 1 shows).</summary>
    public static Stats StatsOver(ReadOnlySpan<Frame> frames, long nowTicks, long windowTicks)
    {
        var (fps, avg) = FpsOver(frames, nowTicks, windowTicks);
        if (fps <= 0) return new Stats(0, 0, 0, double.NaN, false);
        double window = windowTicks / (double)Stopwatch.Frequency, last = frames[^1].T;
        int n = 0, gen = 0, latN = 0, pcN = 0; double latSum = 0, pcSum = 0;
        for (int i = frames.Length - 1; i >= 0; i--)
        {
            var f = frames[i];
            if (last - f.T > window) break;
            n++;
            if (f.Gen) gen++;
            if (float.IsNaN(f.Lat) || f.Gen) continue;
            if (f.PcLat) { pcSum += f.Lat; pcN++; } else { latSum += f.Lat; latN++; }
        }
        double genFps = n > 0 ? fps * gen / n : 0;   // beta2.2: fps counts every frame, FG = the generated share
        // Reflex PC latency wins when the game sends it; otherwise PresentMon's display latency
        double lat = pcN > 0 ? pcSum / pcN : latN > 0 ? latSum / latN : double.NaN;
        return new Stats(fps, genFps, avg, lat, pcN > 0);
    }

    /// <summary>ov.14: smooth graph playback. PresentMon delivers frames in bursts (ETW buffers), so drawing the newest
    /// frames made the graph jump a chunk at a time. This maps PresentMon's clock onto ours (smallest arrival delay seen)
    /// and plays the frames back a burst behind, so the graph scrolls one frame at a time at the game's own pace.</summary>
    public sealed class Playhead
    {
        private double _delay = 0.15;      // target distance behind PresentMon's clock mapped onto ours (s)
        /// <summary>diag (Amine 2026-10-26): A/B of the hold. Adaptive = 2.0.2 behaviour (the default, the only one used
        /// without overlay-diag.json). Fixed = same clock mapping and glide, constant FixedSec instead of the adaptive
        /// delay. Off = the right edge is the newest arrived frame.</summary>
        public OverlayDiag.PlayMode Mode { get; set; } = OverlayDiag.PlayMode.Adaptive;
        public double FixedSec { get; set; } = 0.05;
        /// <summary>diag: the delay used at the last call (s), context only.</summary>
        public double Delay { get; private set; }
        private double _play = double.NaN;  // the playhead on PresentMon's clock (s)
        private long _lastTicks;
        /// <summary>ov.15: the playhead on PresentMon's clock (s) at the last Visible call: the graph's right edge.</summary>
        public double Now { get; private set; }
        /// <summary>How many of frames (oldest first) are due to be shown at nowTicks.
        /// beta2 (Amine: the line stalled, got redrawn and caught up): the playhead only moves forward, at the wall
        /// clock's speed give or take 25 %, gliding toward its target instead of jumping back when a burst makes the
        /// delay grow, and it waits at the newest frame instead of running past it into an empty edge.</summary>
        public int Visible(ReadOnlySpan<Frame> frames, long nowTicks)
        {
            int n = frames.Length;
            if (n == 0) return 0;
            if (Mode == OverlayDiag.PlayMode.Off) { Now = _play = frames[^1].T; _lastTicks = nowTicks; Delay = 0; return n; }
            double f = Stopwatch.Frequency;
            double off = double.MaxValue, worst = 0;
            int from = Math.Max(0, n - 512);
            for (int i = from; i < n; i++) off = Math.Min(off, frames[i].Ticks / f - frames[i].T);
            for (int i = from; i < n; i++) worst = Math.Max(worst, frames[i].Ticks / f - frames[i].T - off);
            worst = Math.Min(worst, 1.2) + 0.03;
            // grow at once on a bigger burst, shrink slowly so the scroll speed doesn't wobble
            _delay = worst > _delay ? worst : _delay + (worst - _delay) * 0.01;
            double hold = Mode == OverlayDiag.PlayMode.Fixed ? FixedSec : _delay;
            Delay = hold;
            double target = nowTicks / f - off - hold, newest = frames[^1].T;
            double dt = _lastTicks == 0 ? 0 : Math.Clamp((nowTicks - _lastTicks) / f, 0, 0.25);
            _lastTicks = nowTicks;
            if (double.IsNaN(_play) || Math.Abs(target - _play) > 1.0) _play = target;   // first call, or a new game / long pause
            else
            {
                double rate = Math.Clamp(1 + (target - _play) * 2, 0.75, 1.25);
                _play = Math.Max(_play, Math.Min(_play + dt * rate, Math.Max(_play, newest)));
            }
            Now = _play;
            int k = n;
            while (k > 0 && frames[k - 1].T > _play) k--;
            return k;
        }
    }

    // ---------- ov.15: stutter and bound ----------

    [ThreadStatic] private static float[]? _medScratch;

    /// <summary>ov.15 stutter: over the last windowSec of PresentMon time, the frames slower than 2x the median frametime.
    /// Generated frames are ignored (they come in pairs with the real one and would halve the median). Returns the
    /// count, the worst one (ms) and the threshold (2x median, 0 when too few frames).</summary>
    public static (int Count, double WorstMs, double ThresholdMs) Stutter(ReadOnlySpan<Frame> frames, double windowSec = 10)
    {
        if (frames.Length == 0) return (0, 0, 0);
        double last = frames[^1].T;
        int from = frames.Length;
        while (from > 0 && last - frames[from - 1].T <= windowSec) from--;
        var buf = _medScratch is { } b && b.Length >= frames.Length - from ? b : (_medScratch = new float[Math.Max(frames.Length - from, 4096)]);
        int n = 0;
        for (int i = from; i < frames.Length; i++) if (!frames[i].Hidden) buf[n++] = frames[i].Ms;
        if (n < 20) return (0, 0, 0);
        // a scratch copy of the window, sorted: the median, then the count from the slow end
        var ms = buf.AsSpan(0, n);
        ms.Sort();
        double median = (n & 1) == 1 ? ms[n / 2] : (ms[n / 2 - 1] + ms[n / 2]) / 2.0;
        double thr = median * 2, worst = 0;
        int count = 0;
        for (int i = n - 1; i >= 0 && ms[i] > thr; i--) { count++; worst = Math.Max(worst, ms[i]); }
        return (count, worst, thr);
    }

    /// <summary>ov.15 bound estimate over the last windowSec: LIMITED when the fps sits at the cap or the V-Sync rate
    /// (limitFps, 0 = none), GPU when the GPU is busy for most of each frame, CPU otherwise. Empty when PresentMon gave
    /// no GPU busy (tracking just started, or this build doesn't report it). An estimate, the overlay says so.</summary>
    public static string Bound(ReadOnlySpan<Frame> frames, double limitFps, double windowSec = 1)
    {
        if (frames.Length == 0) return "";
        double last = frames[^1].T;
        double ms = 0, busy = 0; int n = 0;
        for (int i = frames.Length - 1; i >= 0 && last - frames[i].T <= windowSec; i--)
        {
            var f = frames[i];
            if (f.Gen || f.Hidden || float.IsNaN(f.GpuBusy)) continue;
            ms += f.Ms; busy += f.GpuBusy; n++;
        }
        if (n < 5 || ms <= 0) return "";
        double fps = 1000.0 * n / ms;
        if (limitFps > 0 && fps >= limitFps * 0.96) return "LIMITED";
        return busy / ms >= 0.85 ? "GPU" : "CPU";
    }

