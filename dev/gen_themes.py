def tabler(name):
    s = open(f"{ICONS}/tabler/{name}.svg").read()
    return " ".join(d for d in re.findall(r'<path[^>]*\sd="([^"]+)"', s) if d != "M0 0h24v24H0z")


FG = '{Binding Path=(TextElement.Foreground), RelativeSource={RelativeSource Self}}'


def legend_icons():
    out = ['    <!-- Tabler Icons (MIT, tabler.io): outline, 24 viewBox, stroke 2, round caps/joins -->']
    for k, n in TAB.items():
        out.append(f'    <Viewbox x:Key="Icon.{k}" x:Shared="False" Stretch="Uniform"><Canvas Width="24" Height="24">'
                   f'<Path Data="{tabler(n)}" Stroke="{FG}" StrokeThickness="2" StrokeLineJoin="Round" '
                   f'StrokeStartLineCap="Round" StrokeEndLineCap="Round" /></Canvas></Viewbox>')
    return "\n".join(out)


def fluent_icons():
    out = ['    <!-- Fluent System Icons via WPF-UI SymbolIcon; fan from Phosphor (MIT) -->']
    for k, n in FLU.items():
        out.append(f'    <Viewbox x:Key="Icon.{k}" x:Shared="False" Stretch="Uniform"><ui:SymbolIcon Symbol="{n}" FontSize="24" /></Viewbox>')
    out.append(f'    <Viewbox x:Key="Icon.Fan" x:Shared="False" Stretch="Uniform"><Canvas Width="256" Height="256">'
               f'<Path Data="{PHOSPHOR_FAN}" Fill="{FG}" /></Canvas></Viewbox>')
    return "\n".join(out)


def sp(s):
    """Letter-spacing substitute (WPF has none): thin spaces between letters."""
    return "\u2009".join(s).replace("\u2009 \u2009", "\u2009\u2009 ")


